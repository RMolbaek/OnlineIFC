const DICTS = { en, da, de, hi };
const LOCALES = { en: 'en-GB', da: 'da-DK', de: 'de-DE', hi: 'hi-IN' };
const STORE_KEY = 'onlineifc.lang';

let lang = 'en';
try {
  const saved = localStorage.getItem(STORE_KEY);
  if (saved && DICTS[saved]) lang = saved;
} catch { /* ignore */ }

export function getLang() { return lang; }

export function setLang(l) {
  if (!DICTS[l]) return;
  lang = l;
  try { localStorage.setItem(STORE_KEY, l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}

/** Translates a key. Falls back to English, then to the key itself. */
export function t(key, vars = {}) {
  const v = DICTS[lang][key] ?? en[key];
  if (v === undefined) return key;
  if (typeof v === 'function') return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function fmtNum(n) {
  return Number(n).toLocaleString(LOCALES[lang]);
}

/** Translates static HTML marked with data-i18n, data-i18n-title, data-i18n-placeholder and data-i18n-html. */
export function applyStaticTranslations(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}

